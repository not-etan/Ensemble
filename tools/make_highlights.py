#!/usr/bin/env python3
"""What's new: Ensemble/Highlights.lua from CHANGELOG.md's "### Highlights" blocks.

  python3 tools/make_highlights.py          # write Ensemble/Highlights.lua
  python3 tools/make_highlights.py --check  # fail if Highlights.lua doesn't match CHANGELOG.md

The highlights are written once, in CHANGELOG.md: a "### Highlights" heading inside a version's
"## x.y.z" section, then one bullet per highlight, up to the next heading:

  - **Headline:** One line on what it does. <!-- show: tour -->

The optional comment names a "Show me" target (a key of WhatsNew.SHOW_ME in Tour.lua); it's
hidden on GitHub, and tools/release_notes.py leaves it out of the release notes. A version
without a Highlights block shows nothing in the addon (minor fixes never open the panel).
package.sh runs this; release_notes.py --check and the tests refuse a stale Highlights.lua.
"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
CHANGELOG = os.path.join(ROOT, "CHANGELOG.md")
OUT = os.path.join(ROOT, "Ensemble", "Highlights.lua")

BULLET = re.compile(r"^- \*\*(.+?)\*\*\s*(.*?)\s*(?:<!--\s*show:\s*([\w-]+)\s*-->)?\s*$")


def parse(text):
    """[(version, [(title, text, show or None), ...]), ...] in CHANGELOG order (newest first)."""
    out = []
    for m in re.finditer(r"^## (\d+\.\d+\.\d+)[ \t]*\n(.*?)(?=^## |\Z)", text, re.M | re.S):
        version, body = m.group(1), m.group(2)
        h = re.search(r"^### Highlights[ \t]*\n(.*?)(?=^#|\Z)", body, re.M | re.S)
        if not h:
            continue
        items = []
        for line in h.group(1).splitlines():
            line = line.strip()
            if not line:
                continue
            b = BULLET.match(line)
            if not b:
                sys.exit("CHANGELOG.md %s highlights: not a '- **Headline:** text' bullet: %r" % (version, line))
            title = b.group(1).strip().rstrip(":.").strip()
            body_text = b.group(2).strip()
            if not title or not body_text:
                sys.exit("CHANGELOG.md %s highlights: a headline and a line are both needed: %r" % (version, line))
            # The changelog's style is lowercase after the colon; the panel shows it as a sentence.
            body_text = body_text[0].upper() + body_text[1:]
            items.append((title, body_text, b.group(3)))
        if items:
            out.append((version, items))
    return out


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(groups):
    lines = [
        "-- Ensemble / Highlights.lua",
        "-- GENERATED by tools/make_highlights.py from CHANGELOG.md's \"### Highlights\" blocks.",
        "-- Don't edit by hand: change CHANGELOG.md and run the tool (package.sh does).",
        "-- What's new (Tour.lua, UI:ShowWhatsNew) shows these, newest first.",
        "local _, ns = ...",
        "",
        "ns.HIGHLIGHTS = {",
    ]
    for version, items in groups:
        lines.append("  { version = %s, items = {" % lua_str(version))
        for title, text, show in items:
            extra = (", show = %s" % lua_str(show)) if show else ""
            lines.append("    { title = %s, text = %s%s }," % (lua_str(title), lua_str(text), extra))
        lines.append("  } },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def build():
    return render(parse(open(CHANGELOG, encoding="utf-8").read()))


def current():
    try:
        return open(OUT, encoding="utf-8").read()
    except OSError:
        return None


def main(argv):
    want = build()
    if "--check" in argv:
        if current() != want:
            sys.exit("Ensemble/Highlights.lua doesn't match CHANGELOG.md: run python3 tools/make_highlights.py")
        print("Highlights.lua matches CHANGELOG.md.")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(want)
    print(os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main(sys.argv[1:])
